# ===== CELL 1: Setup + virtual IoT data =====
import numpy as np, pandas as pd, matplotlib.pyplot as plt, seaborn as sns
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import (accuracy_score, precision_score, recall_score, f1_score,
                             roc_auc_score, confusion_matrix, classification_report, roc_curve)

SENSORS = ["temperature", "vibration", "current", "pressure", "rpm"]
HORIZON = 48            # failure within next 48 readings (~8 hours) = 1
WARN, CRIT = 0.50, 0.80 # alert thresholds
SEED = 42

def simulate_machine(mid, rng):
    life = int(rng.integers(600, 1200)); degr = int(rng.integers(90, 160))
    t = np.arange(life); stf = life - 1 - t
    sev = np.clip((t - (life - degr)) / degr, 0, 1) ** 1.8      # 0 healthy -> 1 failing
    b = dict(temperature=rng.normal(62, 3), vibration=rng.normal(2, .2), current=rng.normal(10, .8),
             pressure=rng.normal(100, 4), rpm=rng.normal(1500, 30))
    day = np.sin(2 * np.pi * t / 144)
    df = pd.DataFrame({
        "machine_id": mid,
        "timestamp": pd.Timestamp("2025-01-01") + pd.to_timedelta(t * 10, unit="m"),
        "temperature": b["temperature"] + 2 * day + 28 * sev + rng.normal(0, 1.2, life),
        "vibration": b["vibration"] + .2 * day + 4.5 * sev + rng.normal(0, .25, life),
        "current": b["current"] + .5 * day + 5 * sev + rng.normal(0, .5, life),
        "pressure": b["pressure"] - 18 * sev + rng.normal(0, 2, life),
        "rpm": b["rpm"] - 120 * sev + rng.normal(0, 15, life)})
    sp = rng.random(life) < 0.01
    df.loc[sp, "vibration"] += rng.uniform(1.5, 3, sp.sum())      # harmless spikes
    df["steps_to_failure"] = stf
    df["failure"] = (stf <= HORIZON).astype(int)
    return df

rng = np.random.default_rng(SEED)
raw = pd.concat([simulate_machine(i + 1, rng) for i in range(40)], ignore_index=True)
for c in SENSORS:                                   # simulate sensor dropouts
    raw.loc[rng.random(len(raw)) < 0.01, c] = np.nan

print("Dataset shape:", raw.shape)
print("Failure rate: %.1f%%" % (raw.failure.mean() * 100))
print(raw.head())

# Graph: one machine's sensors before failure
m = raw[raw.machine_id == 1]
fig, ax = plt.subplots(5, 1, figsize=(11, 10), sharex=True)
for a, c in zip(ax, SENSORS):
    a.plot(m.timestamp, m[c], lw=.8); a.set_ylabel(c)
    a.fill_between(m.timestamp, m[c].min(), m[c].max(), where=m.failure == 1, color="red", alpha=.15)
ax[0].set_title("Machine 1: sensors (red = 8 hours before failure)")
plt.tight_layout(); plt.show()

# ===== CELL 2: Cleaning + feature engineering =====
df = raw.sort_values(["machine_id", "timestamp"]).copy()
print("Missing before:", int(df[SENSORS].isna().sum().sum()))
df[SENSORS] = df.groupby("machine_id")[SENSORS].transform(lambda s: s.interpolate(limit_direction="both"))
print("Missing after :", int(df[SENSORS].isna().sum().sum()))

g = df.groupby("machine_id")
for c in SENSORS:
    for w in [6, 18]:                                # 1 hour and 3 hour windows
        df[f"{c}_mean_{w}"] = g[c].transform(lambda s: s.rolling(w, min_periods=1).mean())
        df[f"{c}_std_{w}"] = g[c].transform(lambda s: s.rolling(w, min_periods=1).std()).fillna(0)
    df[f"{c}_diff"] = g[c].diff().fillna(0)
df["power_proxy"] = df["current"] * df["rpm"] / 1000
df["heat_vib_ratio"] = df["temperature"] / (df["vibration"] + 1e-6)

FEATS = [c for c in df.columns if c not in ("machine_id", "timestamp", "failure", "steps_to_failure")]
print("Number of features:", len(FEATS))

fig, ax = plt.subplots(1, 2, figsize=(11, 4))
sns.countplot(x="failure", data=df, ax=ax[0]); ax[0].set_title("Class balance (imbalanced!)")
sns.heatmap(df[SENSORS + ["failure"]].corr(), annot=True, fmt=".2f", cmap="coolwarm", ax=ax[1])
ax[1].set_title("Correlation"); plt.tight_layout(); plt.show()

# ===== CELL 3: Train + evaluate (split by MACHINE to avoid leakage) =====
tr_i, te_i = next(GroupShuffleSplit(test_size=.25, random_state=SEED).split(df, groups=df.machine_id))
train, test = df.iloc[tr_i], df.iloc[te_i].copy()
print("Train machines:", train.machine_id.nunique(), "| Test machines:", test.machine_id.nunique())

models = {
    "Logistic Regression": make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000, class_weight="balanced")),
    "Random Forest": RandomForestClassifier(n_estimators=200, max_depth=12, min_samples_leaf=5,
                                            class_weight="balanced", n_jobs=-1, random_state=SEED)}
results = {}
for name, mdl in models.items():
    mdl.fit(train[FEATS], train.failure)
    p = mdl.predict_proba(test[FEATS])[:, 1]; yp = (p >= WARN).astype(int); y = test.failure
    results[name] = dict(accuracy=accuracy_score(y, yp), precision=precision_score(y, yp),
                         recall=recall_score(y, yp), f1=f1_score(y, yp), roc_auc=roc_auc_score(y, p))
res = pd.DataFrame(results).T.round(3)
print(res)
res.plot.bar(figsize=(8, 4), rot=0, ylim=(0, 1.05), title="Model comparison"); plt.show()

best = res.f1.idxmax(); model = models[best]; print("\nBest model:", best)
test["failure_prob"] = model.predict_proba(test[FEATS])[:, 1]
pred = (test.failure_prob >= WARN).astype(int)
print(classification_report(test.failure, pred, target_names=["Normal", "Failure soon"]))

fig, ax = plt.subplots(1, 2, figsize=(11, 4))
sns.heatmap(confusion_matrix(test.failure, pred), annot=True, fmt="d", cmap="Blues", ax=ax[0],
            xticklabels=["Normal", "Failure"], yticklabels=["Normal", "Failure"])
ax[0].set_xlabel("Predicted"); ax[0].set_ylabel("Actual"); ax[0].set_title("Confusion matrix")
fpr, tpr, _ = roc_curve(test.failure, test.failure_prob)
ax[1].plot(fpr, tpr); ax[1].plot([0, 1], [0, 1], "--", c="gray"); ax[1].set_title("ROC curve")
plt.tight_layout(); plt.show()

# ===== CELL 4: Alerts + failure prediction graph + live simulation =====
test["alert"] = np.where(test.failure_prob >= CRIT, "CRITICAL",
                 np.where(test.failure_prob >= WARN, "WARNING", "OK"))

rows = []
for mid, gg in test.groupby("machine_id"):
    w = gg[gg.alert != "OK"]
    rows.append(dict(machine_id=mid, level=w.alert.iloc[0] if len(w) else "MISSED",
                     hours_before_failure=round(w.steps_to_failure.iloc[0] * 10 / 60, 1) if len(w) else 0))
alerts = pd.DataFrame(rows); print(alerts.to_string(index=False))
print("\nAverage warning lead time: %.1f hours" % alerts.hours_before_failure.mean())

demo = test.machine_id.iloc[0]; d = test[test.machine_id == demo]
fig, ax = plt.subplots(2, 1, figsize=(11, 6), sharex=True)
ax[0].plot(d.timestamp, d.temperature, label="temperature"); ax[0].plot(d.timestamp, d.vibration * 10, label="vibration x10")
ax[0].legend(); ax[0].set_title(f"Machine {demo}: failure prediction")
ax[1].plot(d.timestamp, d.failure_prob, c="purple", label="failure probability")
ax[1].axhline(WARN, ls="--", c="orange", label="WARNING"); ax[1].axhline(CRIT, ls="--", c="red", label="CRITICAL")
ax[1].fill_between(d.timestamp, 0, 1, where=d.failure == 1, color="red", alpha=.12, label="True failure zone")
ax[1].legend(loc="upper left"); plt.tight_layout(); plt.show()

# Feature importance
clf = model.steps[-1][1] if hasattr(model, "steps") else model
imp = clf.feature_importances_ if hasattr(clf, "feature_importances_") else abs(clf.coef_[0])
pd.Series(imp, index=FEATS).nlargest(12)[::-1].plot.barh(figsize=(7, 5), title="Top features"); plt.show()

# Live simulation (prints every 2 hours)
print("\n--- LIVE SIMULATION: machine", demo, "---")
for _, r in d.iloc[::12].iterrows():
    icon = {"OK": "✅", "WARNING": "⚠️", "CRITICAL": "🚨"}[r.alert]
    if r.alert != "OK" or r.name % 10 == 0:
        print(f"{r.timestamp}  T={r.temperature:.1f}C  V={r.vibration:.2f}  P(fail)={r.failure_prob:.2f}  {icon} {r.alert}")
    if r.alert == "CRITICAL": print("   -> Motor OFF + maintenance ticket (simulated)")

print("\nSave your outputs: alerts.to_csv('alert_log.csv', index=False)")

